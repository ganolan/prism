#!/usr/bin/env node
/**
 * Generates Prism's favicon from the same ray-trace as the sidebar logo
 * (client/src/lib/prismOptics.js), then renders the PNG sizes browsers without
 * SVG favicon support need (Safari; iOS home screen / bookmarks):
 *   client/public/favicon.svg, favicon-32.png, apple-touch-icon.png (180×180).
 * Re-run after changing the optics or the colours:  node scripts/render-favicons.mjs
 */
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  APEX, BASE_Y, RIDGE_X, SHADED_FACE, TRIANGLE, beamShapes, exitBeam, polygon,
} from '../client/src/lib/prismLogoGeometry.js';

const pub = join(dirname(fileURLToPath(import.meta.url)), '..', 'client', 'public');

// Hex, not CSS variables: a favicon is a standalone file. Beam colours match
// the --brand-* variables in client/src/app.css.
const COLOURS = { teal: '#14d3a6', blue: '#1ea7fd', violet: '#8b55e0' };
export const COSMIC_COBALT = '#2e2d88';

// A light tile, like the concept art's page: the beam out is cosmic cobalt, and
// a dark tile would swallow it. The outline is the one strong line that holds
// the shape at 16px.
export const PALETTE = {
  tileTop: '#ffffff',
  tileBottom: '#eceef9',
  tileEdge: '#cfd3ec', // keeps a white tile from dissolving into a white bookmark bar
  glass: '#e6ecf7',
  glassOpacity: 0.55, // over the beams inside, which turns them pastel
  shade: '#5d6f9e',
  shadeOpacity: 0.12,
  ridge: '#9fb0d4',
  outline: '#7f93c4',
  exit: COSMIC_COBALT,
};

// A square crop of the logo's mark, in the concept art's pixel coordinates.
const TILE = { x: 180, y: 185, size: 590 };
const WEIGHT = 1.5; // heavier beams, so they survive 16px
// The beam out is cosmic cobalt and 1.6× the other beams' weight, so it reads
// as the one combined beam at 16px, where the logo's gradient underline can't.
const EXIT_WEIGHT = WEIGHT * 1.6;

export function faviconSvg({ rounded = true, palette = PALETTE } = {}) {
  const { x, y, size } = TILE;
  const c = palette;
  const beams = beamShapes({ weight: WEIGHT });
  const r = rounded ? ` rx="${size * 0.22}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${size} ${size}">
  <!-- GENERATED by scripts/render-favicons.mjs from client/src/lib/prismLogoGeometry.js;
       edit those, not this file. -->
  <defs>
    <clipPath id="tile"><rect x="${x}" y="${y}" width="${size}" height="${size}"${r}/></clipPath>
    <linearGradient id="bg" x1="0" x2="0" y1="0" y2="1">
      <stop offset="0" stop-color="${c.tileTop}"/>
      <stop offset="1" stop-color="${c.tileBottom}"/>
    </linearGradient>
  </defs>
  <g clip-path="url(#tile)">
    <rect x="${x}" y="${y}" width="${size}" height="${size}" fill="url(#bg)"/>
${beams
  .map(
    (b) =>
      `    <path d="${polygon(b.outside)}" fill="${COLOURS[b.colour]}"/>\n` +
      `    <path d="${polygon(b.inside)}" fill="${COLOURS[b.colour]}"/>`,
  )
  .join('\n')}
    <path d="${TRIANGLE}" fill="${c.glass}" fill-opacity="${c.glassOpacity}"/>
    <path d="${SHADED_FACE}" fill="${c.shade}" fill-opacity="${c.shadeOpacity}"/>
    <line x1="${RIDGE_X}" y1="${APEX.y}" x2="${RIDGE_X}" y2="${BASE_Y}" stroke="${c.ridge}" stroke-width="10"/>
    <path d="${TRIANGLE}" fill="none" stroke="${c.outline}" stroke-width="22" stroke-linejoin="round"/>
    <path d="${polygon(exitBeam({ weight: EXIT_WEIGHT, endX: x + size + 10 }))}" fill="${c.exit}"/>
  </g>
  ${rounded ? `<rect x="${x + 4}" y="${y + 4}" width="${size - 8}" height="${size - 8}"${r} fill="none" stroke="${c.tileEdge}" stroke-width="8"/>` : ''}
</svg>
`;
}

// iOS rounds the touch icon itself and paints transparent corners black, so
// that one is rendered full-bleed.
const TARGETS = [
  { file: 'favicon-32.png', size: 32, svg: faviconSvg() },
  { file: 'apple-touch-icon.png', size: 180, svg: faviconSvg({ rounded: false }) },
];

writeFileSync(join(pub, 'favicon.svg'), faviconSvg());
console.log('wrote favicon.svg');

const browser = await chromium.launch();
try {
  for (const { file, size, svg } of TARGETS) {
    const page = await browser.newPage({ viewport: { width: size, height: size } });
    await page.setContent(
      `<style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${svg}`,
    );
    await page.screenshot({ path: join(pub, file), omitBackground: true });
    await page.close();
    console.log(`wrote ${file} (${size}×${size})`);
  }
} finally {
  await browser.close();
}
