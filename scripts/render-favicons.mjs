#!/usr/bin/env node
/**
 * Generates Prism's favicon from the same ray-trace as the sidebar logo
 * (client/src/lib/prismOptics.js), then renders the PNG sizes browsers without
 * SVG favicon support need (Safari; iOS home screen / bookmarks):
 *   client/public/favicon.svg, favicon-32.png, apple-touch-icon.png (180×180).
 * Re-run after changing the optics or the colours:  node scripts/render-favicons.mjs
 */
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tracePrism } from '../client/src/lib/prismOptics.js';

const pub = join(dirname(fileURLToPath(import.meta.url)), '..', 'client', 'public');

// Hex, not CSS variables: a favicon is a standalone file. Keep in step with
// the --brand-* variables and the Prism theme's sidebar in client/src/app.css.
const COLOURS = { teal: '#14d3a6', blue: '#1ea7fd', violet: '#8b55e0' };
const TILE_TOP = '#2d1b69';
const TILE_BOTTOM = '#1e1145';

const { triangle, exit, beams } = tracePrism({ apex: { x: 36, y: 8 }, height: 44, exitY: 32, leftX: -8 });
const pt = (p) => `${p.x.toFixed(2)} ${p.y.toFixed(2)}`;

export function faviconSvg({ rounded = true } = {}) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- GENERATED by scripts/render-favicons.mjs from client/src/lib/prismOptics.js;
       edit those, not this file. Prism's mark on the Prism theme's sidebar purple. -->
  <defs>
    <clipPath id="tile"><rect width="64" height="64"${rounded ? ' rx="14"' : ''}/></clipPath>
    <linearGradient id="bg" x1="0" x2="0" y1="0" y2="1">
      <stop offset="0" stop-color="${TILE_TOP}"/>
      <stop offset="1" stop-color="${TILE_BOTTOM}"/>
    </linearGradient>
    <linearGradient id="out" x1="0" x2="1">
      <stop offset="0" stop-color="${COLOURS.teal}"/>
      <stop offset="0.5" stop-color="${COLOURS.blue}"/>
      <stop offset="1" stop-color="${COLOURS.violet}"/>
    </linearGradient>
  </defs>
  <g clip-path="url(#tile)">
    <rect width="64" height="64" fill="url(#bg)"/>
    <g fill="none">
${beams
  .map(
    (b) =>
      `      <path d="M${pt(b.start)} L${pt(b.entry)}" stroke="${COLOURS[b.colour]}" stroke-width="6"/>\n` +
      `      <path d="M${pt(b.entry)} L${pt(exit)}" stroke="${COLOURS[b.colour]}" stroke-width="4" stroke-opacity="0.6"/>`,
  )
  .join('\n')}
    </g>
    <path d="M${triangle.map(pt).join(' L')} Z" fill="#ffffff" fill-opacity="0.14" stroke="#ffffff" stroke-width="3.4" stroke-linejoin="round"/>
    <rect x="${exit.x.toFixed(2)}" y="${(exit.y - 3).toFixed(2)}" width="${(66 - exit.x).toFixed(2)}" height="6" fill="url(#out)"/>
  </g>
</svg>
`;
}

// iOS rounds the touch icon itself and paints transparent corners black, so
// that one is rendered full-bleed.
const TARGETS = [
  { file: 'favicon-32.png', size: 32, svg: faviconSvg() },
  { file: 'apple-touch-icon.png', size: 180, svg: faviconSvg({ rounded: false }) },
];

writeFileSync(join(pub, 'favicon.svg'), faviconSvg());
console.log('wrote favicon.svg');

const browser = await chromium.launch();
try {
  for (const { file, size, svg } of TARGETS) {
    const page = await browser.newPage({ viewport: { width: size, height: size } });
    await page.setContent(
      `<style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${svg}`,
    );
    await page.screenshot({ path: join(pub, file), omitBackground: true });
    await page.close();
    console.log(`wrote ${file} (${size}×${size})`);
  }
} finally {
  await browser.close();
}
